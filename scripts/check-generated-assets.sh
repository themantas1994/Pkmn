#!/usr/bin/env bash
# CI guard: assets/ and reports/ are generated (from data-src/, world/ and the audits). After regenerating, nothing under
# them may differ from the commit: no modified/deleted tracked file AND no new untracked file (git diff alone misses the latter).
# Usage: scripts/check-generated-assets.sh [--reports] [repo-dir]   (repo-dir defaults to the current directory)
#   (default)  check assets/
#   --reports  check reports/, except the host-specific files listed in HOST_REPORTS (not produced by the CI steps, or
#              dependent on the machine: timings, local sprite coverage)
#   --restore-host-reports  git-checkout the host-specific reports that GATES_DIRTY_BEFORE does not list (used by scripts/gates.sh)
set -euo pipefail
# Reports that are NOT deterministic across machines or are not regenerated by the CI gates.
HOST_REPORTS=(reports/sprite-coverage.json reports/performance.json reports/playtime.json reports/capture.json reports/capture.md reports/mechanics-checklist.json)
mode=assets
case "${1:-}" in
  --reports) mode=reports; shift ;;
  --restore-host-reports) mode=restore; shift ;;
esac
cd "${1:-.}"
case "$mode" in
  restore)
    # Files named in GATES_DIRTY_BEFORE (newline separated) were already modified before the run and are kept.
    for f in "${HOST_REPORTS[@]}"; do
      git ls-files --error-unmatch -- "$f" >/dev/null 2>&1 || continue
      grep -qxF "$f" <<<"${GATES_DIRTY_BEFORE:-}" && continue
      git checkout -q -- "$f"
    done
    exit 0 ;;
  reports)
    excludes=(); for f in "${HOST_REPORTS[@]}"; do excludes+=(":(exclude)$f"); done
    dirty="$(git status --porcelain --untracked-files=all -- reports/ "${excludes[@]}")"
    if [ -n "$dirty" ]; then
      echo "Generated reports under reports/ are not committed (rerun the audits and commit the result):" >&2
      echo "$dirty" >&2
      git diff --stat -- reports/ "${excludes[@]}" >&2 || true
      exit 1
    fi
    echo "reports/ is clean"
    exit 0 ;;
esac
dirty="$(git status --porcelain --untracked-files=all -- assets/)"
if [ -n "$dirty" ]; then
  echo "Generated content under assets/ is not committed (regenerate with the content gates and commit):" >&2
  echo "$dirty" >&2
  exit 1
fi
echo "assets/ is clean"
