package pkmn.tools

import kotlinx.serialization.json.*

/** Renders reports/COVERAGE.md purely from the generated JSON reports (numbers only, no hand-written claims). */
object CoverageMarkdown {
    fun render(reports: Map<String, JsonObject>): String = buildString {
        appendLine("# Content coverage")
        appendLine()
        appendLine("Generated by `./gradlew :tools:validateContent` from the JSON files in this directory. Do not edit by hand.")
        appendLine()
        reports["content-validation.json"]?.let { v ->
            appendLine("## Validation (`content-validation.json`)")
            appendLine()
            appendLine("- ok: ${v.p("ok")}; errors: ${v.p("errorCount")}; warnings: ${v.p("warningCount")}")
            table("Warnings by code", v.o("warningsByCode"))
            table("Errors by code", v.o("errorsByCode"))
        }
        reports["coverage-species.json"]?.let { s ->
            appendLine("## Species (`coverage-species.json`)")
            appendLine()
            appendLine("- Species entries: ${s.p("speciesEntries")} (base species: ${s.p("baseSpecies")} / expected ${s.p("expectedBaseSpecies")}; battle-only entries: ${s.p("battleOnlyEntries")})")
            s.o("learnsets")?.let { appendLine("- Learnsets: ${it.p("entries")} entries; non-battle-only species resolving a level-up learnset: ${it.p("nonBattleOnlyResolved")} / ${it.p("nonBattleOnlySpecies")}") }
            s.o("catchRates")?.let { appendLine("- Catch rates: ${it.p("baseSpeciesWithPokeApiCaptureRate")} base species from PokeAPI, ${it.p("baseSpeciesUsingDefault")} using the default; range ${it.p("min")}..${it.p("max")}") }
            s.o("evolutions")?.let { appendLine("- Evolution edges: ${it.p("edges")}; species that evolve: ${it.p("speciesThatEvolve")}") }
            appendLine("- Legendary: ${s.p("legendary")}; Mythical: ${s.p("mythical")}")
            table("Forms by kind", s.o("formsByKind"))
            table("Base species by generation", s.o("baseSpeciesByGeneration"))
            s.o("sprites")?.let { sp ->
                appendLine("| Sprite kind | base species with sprite | missing | forms with sprite | bundled files | local files |")
                appendLine("|---|---|---|---|---|---|")
                for ((k, v) in sp) if (v is JsonObject) appendLine("| $k | ${v.p("baseSpeciesWithSprite")} | ${v.p("baseSpeciesMissing")} | ${v.p("formsWithSprite")} | ${v.p("bundledFiles")} | ${v.p("localFiles")} |")
                appendLine()
            }
        }
        reports["coverage-forms.json"]?.let { f ->
            appendLine("## Forms (`coverage-forms.json`)")
            appendLine()
            appendLine("- Total non-base forms: ${f.p("total")}; cosmetic formes: ${f.p("cosmeticFormes")}; species with canGigantamax: ${f.p("speciesWithCanGigantamax")}")
            appendLine()
        }
        reports["coverage-items.json"]?.let { i ->
            appendLine("## Items (`coverage-items.json`)")
            appendLine()
            appendLine("- Total: ${i.p("total")}; with battle data: ${i.p("withBattleData")}")
            i.o("evolutionItems")?.let { appendLine("- Evolution items referenced by evolutions: ${it.p("referencedByEvolutions")} (EVOLUTION category items: ${it.p("categoryEVOLUTION")})") }
            i.o("megaStones")?.let { appendLine("- Mega Stones: ${it.p("count")}") }
            i.o("zCrystals")?.let { appendLine("- Z-Crystals: ${it.p("count")} (type: ${it.p("typeCrystals")}, exclusive: ${it.p("exclusiveCrystals")})") }
            table("Items by category", i.o("byCategory"))
        }
        reports["coverage-evolutions.json"]?.let { e ->
            appendLine("## Evolutions (`coverage-evolutions.json`)")
            appendLine()
            appendLine("- Edges: ${e.p("edges")}; satisfiable in-game: ${e.p("satisfiable")}; unsatisfiable: ${e.p("unsatisfiable")} (region: ${e.p("gameRegion")})")
            table("By method", e.o("byMethod"))
            (e["unsatisfiableEvolutions"] as? JsonArray)?.takeIf { it.isNotEmpty() }?.let { arr ->
                appendLine("| Unsatisfiable | condition code | reason |")
                appendLine("|---|---|---|")
                for (x in arr) { val o = x.jsonObject; appendLine("| ${o.p("from")} -> ${o.p("to")} | ${o["conditionCode"]?.jsonPrimitive?.content ?: ""} | ${o.p("reason")} |") }
                appendLine()
            }
        }
        reports["coverage-registered.json"]?.let { r ->
            appendLine("## Registered battle effects (`coverage-registered.json`)")
            appendLine()
            appendLine("| Kind | registered | total | percent |")
            appendLine("|---|---|---|---|")
            for (k in listOf("abilities", "items", "moveScripts", "conditions")) r.o(k)?.let {
                appendLine("| $k | ${it.p("registered")} | ${it["total"]?.jsonPrimitive?.content ?: "n/a"} | ${it["percent"]?.jsonPrimitive?.content ?: "n/a"} |")
            }
            appendLine()
        }
        appendLine("## Battle mechanics coverage (`BattleCoverage`)")
        appendLine()
        for (f in listOf("coverage-moves.json", "coverage-abilities.json", "coverage-held-items.json")) {
            val r = reports[f] ?: continue
            if (r["available"]?.jsonPrimitive?.boolean == true) {
                val counts = r.o("byStatus")?.entries?.joinToString(", ") { "${it.key}: ${it.value.jsonPrimitive.content}" }
                appendLine("- `$f`: ${r.p("reported")} reported of ${r.p("totalInDex")} — $counts")
            } else appendLine("- `$f`: unavailable (${r.p("reason")})")
        }
    }

    private fun JsonObject.p(k: String) = (this[k] as? JsonPrimitive)?.content ?: ""
    private fun JsonObject.o(k: String) = this[k] as? JsonObject

    private fun StringBuilder.table(title: String, o: JsonObject?) {
        if (o == null || o.isEmpty()) return
        appendLine()
        appendLine("| $title | count |")
        appendLine("|---|---|")
        for ((k, v) in o) appendLine("| $k | ${v.jsonPrimitive.content} |")
        appendLine()
    }
}
