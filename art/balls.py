def render(ball):
    bottom, accent, top, outline, pat = BALLS[ball]
    palette = pal(bottom, accent, top, outline)
    a = BASE.copy()
    t_lines, b_lines = PATTERNS[pat]
    for rows, lines in ((TOP_ROWS, t_lines), (BOT_ROWS, b_lines)):
        for y, line in zip(rows, lines):
            assert len(line) == 16, (pat, y)
            for x, ch in enumerate(line):
                if ch != "." and a[y, x] in (0, 1, 2):
                    a[y, x] = int(ch)
    return pixlib.to_rgba(a, palette)


def build():
    out = os.path.join(pixlib.GFX, "balls")
    for name in BALLS:
        pixlib.save_png(render(name), os.path.join(out, name + ".png"))
    import hashlib
    seen = {}
    for name in BALLS:
        with open(os.path.join(out, name + ".png"), "rb") as f:
            d = hashlib.md5(f.read()).hexdigest()
        assert d not in seen, f"ball icons {name} and {seen[d]} are identical"
        seen[d] = name


if __name__ == "__main__":
    build()
