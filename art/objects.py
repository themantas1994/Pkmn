def legendary_shadow():
    """Generic winged silhouette (32x32) for legendary encounter events.
    Drawn as the left half and mirrored."""
    half = grid(LEGEND_HALF)
    a = np.hstack([half, half[:, ::-1]])
    a = pixlib.outline(a, 3)
    return a


def build():
    out = os.path.join(pixlib.GFX, "objects")
    for name, (p, g) in OBJECTS.items():
        assert g.shape == (16, 16), name
        pixlib.save_png(pixlib.to_rgba(g, p), os.path.join(out, name + ".png"))
    ls = legendary_shadow()
    assert ls.shape == (32, 32)
    pixlib.save_png(pixlib.to_rgba(ls, SHADOW), os.path.join(out, "legendary_shadow.png"))


if __name__ == "__main__":
    build()
